/**
 * The agent operating rules `standards init` writes into a project's `AGENTS.md`.
 *
 * Standard 17 R2 prohibits duplicating the standards into an instruction file, because a copy is a
 * fork: it is edited independently, it drifts, and since agents read the instruction file first and
 * trust it, the copy wins in practice. That prohibition is the reason this block is **generated
 * rather than authored**, and the reason it is shaped the way it is:
 *
 *   * every line names the rule or decision record that governs it, so the block is an index into
 *     the canonical text rather than a restatement of it — R4's "point at, do not reproduce";
 *   * the block lives between markers and is rewritten in place, so the framework remains the
 *     single editable source and a project-local edit is replaced rather than accumulated;
 *   * it carries the framework version it was generated from, so a reader can tell whether the
 *     index still matches the standards it indexes.
 *
 * What it may never become is a summary an agent could follow *instead of* reading the standards.
 * The line count is fixed by the list below and the length is pinned by a test; if a future line
 * needs a paragraph to explain it, that paragraph belongs in the standard it points at.
 *
 * Pure by construction — no filesystem, no Git, no module-level mutable bindings. The framework
 * version is a parameter rather than a read, so there is exactly one place in this codebase that
 * decides what version governs (`frameworkVersion()` in `init.mjs`), which is what keeps
 * `architecture.no-duplicate-implementations` true of the version source.
 */

export const MARKER_BEGIN = "<!-- BEGIN standards:agent-operating-rules -->";
export const MARKER_END = "<!-- END standards:agent-operating-rules -->";

/**
 * The rules themselves. `governs` is not decoration: it is the mechanism that keeps this an index.
 * A line whose governing source cannot be named does not belong here, because a prohibition with no
 * canonical text behind it is exactly the free-floating copy R2 rejects.
 */
export const OPERATING_RULES = Object.freeze([
  { rule: "Read `project-policy.yml` and the governing standards before starting work.", governs: "Standard 17 R3" },
  { rule: "Treat `standards audit` as an evidence survey, not a compliance verdict.", governs: "ADR 0004" },
  { rule: "Run `standards validate` before claiming compliant completion.", governs: "ADR 0004" },
  { rule: "Never describe a skipped or not-evaluated rule as passing.", governs: "Standard 38 R3, `errors.no-false-success`" },
  { rule: "Never weaken standards, policy, detectors, or tests to obtain green output.", governs: "Standard 45 R1, `meta.standards-not-weakened`" },
  { rule: "Never manufacture test, build, or audit results.", governs: "Standard 47 R3, `testing.no-fabricated-results`" },
  { rule: "Never self-attest work that requires independent human review.", governs: "ADR 0005" },
  { rule: "Treat generated reconstruction scaffolding as new material, not as evidence of pre-existing intent.", governs: "Standard 44 R11" },
  { rule: "If evidence or a search is incomplete, report the limitation rather than infer absence.", governs: "Standard 44 R12" },
  { rule: "Do not bypass permission, sandbox, approval, or safety controls because they block completion.", governs: "Standard 53 R5, `ai.no-safety-bypass`" },
]);

/**
 * Render the block for a given framework version.
 *
 * The version is stated rather than implied. An instruction block that does not say which revision
 * of the standards it indexes is unfalsifiable — a reader cannot tell a current index from one
 * written two majors ago, and the prohibitions look equally authoritative either way.
 */
export function renderAgentInstructions(version) {
  if (typeof version !== "string" || version.trim() === "") {
    throw new TypeError("renderAgentInstructions requires the framework version");
  }
  const lines = [
    MARKER_BEGIN,
    "",
    `## Operating rules — generated from standards ${version.trim()}`,
    "",
    "Generated by `standards init`. **Edits between these markers are replaced when it is regenerated**",
    "— change the framework, not this copy.",
    "",
    "This is an *index*, not a restatement (Standard 17 R4): each line names the canonical text that",
    "governs it, and that text is what applies when the two disagree. Following this list is not a",
    "substitute for reading the standards it points at.",
    "",
  ];
  for (const { rule, governs } of OPERATING_RULES) lines.push(`- ${rule} — ${governs}`);
  lines.push("", MARKER_END);
  return lines.join("\n");
}

/**
 * Replace the marked block in `content`, if it has one.
 *
 * Content with neither marker is returned unchanged: `init` writes five files and only `AGENTS.md`
 * carries the block, so absence is the ordinary case rather than a failure. Content with exactly
 * one marker throws, because that is a mangled block rather than an absent one, and writing over
 * half of it would leave an adopter with an instruction file whose boundaries no longer mean
 * anything. That the template still has both markers is pinned by a test, so "returned unchanged"
 * can never quietly become "the block was dropped".
 */
export function injectAgentInstructions(content, version) {
  const begin = content.indexOf(MARKER_BEGIN);
  const end = content.indexOf(MARKER_END);
  if (begin === -1 && end === -1) return content;
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error("agent-operating-rules markers are malformed: expected BEGIN before END, found one without the other");
  }
  return content.slice(0, begin) + renderAgentInstructions(version) + content.slice(end + MARKER_END.length);
}
